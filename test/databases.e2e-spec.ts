import { jest, describe, it, expect, beforeAll, afterAll } from '@jest/globals';
import { Test, TestingModule } from '@nestjs/testing';
import {
  INestApplication,
  NotFoundException,
  ValidationPipe,
} from '@nestjs/common';
import { PassportModule } from '@nestjs/passport';
import { JwtModule, JwtService } from '@nestjs/jwt';
import request from 'supertest';
import { App } from 'supertest/types';
import { DatabasesController } from '../src/databases/databases.controller.js';
import { DatabasesService } from '../src/databases/databases.service.js';
import { JwtStrategy } from '../src/auth/strategies/jwt.strategy.js';
import { UsersService } from '../src/users/users.service.js';
import { ProjectDatabase } from '../src/databases/entities/project-database.entity.js';
import { DatabaseType } from '../src/databases/enums/database-type.enum.js';
import { DatabaseStatus } from '../src/databases/enums/database-status.enum.js';

describe('DatabasesController (e2e)', () => {
  let app: INestApplication<App>;
  let jwtService: JwtService;
  let authToken: string;

  const mockUser = {
    id: 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11',
    email: 'developer@titanpaas.local',
    name: 'Dev User',
    createdAt: new Date(),
    updatedAt: new Date(),
  };

  const projectId = 'b0eebc99-9c0b-4ef8-bb6d-6bb9bd380a22';
  const databaseId = 'c0eebc99-9c0b-4ef8-bb6d-6bb9bd380a33';

  const databaseStore = new Map<string, ProjectDatabase>();

  const mockDatabasesService = {
    create: jest.fn((_userId: string, pid: string, dto: any) => {
      const port =
        dto.type === DatabaseType.POSTGRESQL
          ? 5432
          : dto.type === DatabaseType.MYSQL
            ? 3306
            : 6379;
      const containerName = `titan_db_repo_${dto.name}`;
      const volumeName = `titan_vol_db_repo_${dto.name}`;
      const password = dto.password || 'autogenerated_pass_123';
      const databaseName =
        dto.type === DatabaseType.REDIS ? null : dto.databaseName || 'app_db';
      const username =
        dto.type === DatabaseType.REDIS
          ? null
          : dto.username ||
            (dto.type === DatabaseType.MYSQL ? 'root' : 'titan_user');

      const connectionUrl =
        dto.type === DatabaseType.REDIS
          ? `redis://:${password}@${containerName}:${port}`
          : dto.type === DatabaseType.POSTGRESQL
            ? `postgresql://${username}:${password}@${containerName}:${port}/${databaseName}`
            : `mysql://${username}:${password}@${containerName}:${port}/${databaseName}`;

      const db: ProjectDatabase = {
        id: databaseId,
        name: dto.name,
        type: dto.type,
        version: dto.version || 'latest',
        status: DatabaseStatus.RUNNING,
        containerName,
        containerId: 'docker-cid-test-1',
        volumeName,
        port,
        databaseName,
        username,
        password,
        connectionUrl,
        projectId: pid,
        project: null as any,
        createdAt: new Date(),
        updatedAt: new Date(),
      };
      databaseStore.set(databaseId, db);
      return Promise.resolve(db);
    }),
    findAllByProject: jest.fn((_userId: string, pid: string) => {
      const list = Array.from(databaseStore.values()).filter(
        (d) => d.projectId === pid,
      );
      return Promise.resolve(list);
    }),
    findOne: jest.fn((_userId: string, _pid: string, id: string) => {
      const db = databaseStore.get(id);
      if (!db) {
        throw new NotFoundException(`Base de datos #${id} no encontrada`);
      }
      return Promise.resolve(db);
    }),
    getCredentials: jest.fn((_userId: string, _pid: string, id: string) => {
      const db = databaseStore.get(id);
      if (!db) {
        throw new NotFoundException(`Base de datos #${id} no encontrada`);
      }
      return Promise.resolve({
        host: db.containerName,
        port: db.port,
        databaseName: db.databaseName,
        username: db.username,
        password: db.password,
        connectionUrl: db.connectionUrl,
      });
    }),
    start: jest.fn((_userId: string, _pid: string, id: string) => {
      const db = databaseStore.get(id);
      if (!db) {
        throw new NotFoundException(`Base de datos #${id} no encontrada`);
      }
      db.status = DatabaseStatus.RUNNING;
      return Promise.resolve(db);
    }),
    stop: jest.fn((_userId: string, _pid: string, id: string) => {
      const db = databaseStore.get(id);
      if (!db) {
        throw new NotFoundException(`Base de datos #${id} no encontrada`);
      }
      db.status = DatabaseStatus.STOPPED;
      return Promise.resolve(db);
    }),
    restart: jest.fn((_userId: string, _pid: string, id: string) => {
      const db = databaseStore.get(id);
      if (!db) {
        throw new NotFoundException(`Base de datos #${id} no encontrada`);
      }
      db.status = DatabaseStatus.RUNNING;
      return Promise.resolve(db);
    }),
    remove: jest.fn((_userId: string, _pid: string, id: string) => {
      const db = databaseStore.get(id);
      if (!db) {
        throw new NotFoundException(`Base de datos #${id} no encontrada`);
      }
      databaseStore.delete(id);
      return Promise.resolve({
        message: `Base de datos "${db.name}" eliminada exitosamente`,
      });
    }),
  };

  const mockUsersService = {
    findById: jest.fn((id: string) => {
      if (id === mockUser.id) return Promise.resolve(mockUser);
      return Promise.resolve(null);
    }),
  };

  beforeAll(async () => {
    const moduleRef: TestingModule = await Test.createTestingModule({
      imports: [
        PassportModule.register({ defaultStrategy: 'jwt' }),
        JwtModule.register({
          secret: 'titan_paas_secret_key_change_in_prod',
          signOptions: { expiresIn: '1d' },
        }),
      ],
      controllers: [DatabasesController],
      providers: [
        JwtStrategy,
        {
          provide: DatabasesService,
          useValue: mockDatabasesService,
        },
        {
          provide: UsersService,
          useValue: mockUsersService,
        },
      ],
    }).compile();

    app = moduleRef.createNestApplication();
    app.useGlobalPipes(
      new ValidationPipe({
        whitelist: true,
        forbidNonWhitelisted: true,
        transform: true,
      }),
    );
    await app.init();

    jwtService = moduleRef.get<JwtService>(JwtService);
    authToken = jwtService.sign({
      sub: mockUser.id,
      email: mockUser.email,
    });
  });

  afterAll(async () => {
    if (app) {
      await app.close();
    }
  });

  describe('POST /projects/:projectId/databases', () => {
    it('should reject requests without authorization token (401)', async () => {
      await request(app.getHttpServer())
        .post(`/projects/${projectId}/databases`)
        .send({ name: 'main-postgres', type: 'postgres' })
        .expect(401);
    });

    it('should reject invalid database type (400)', async () => {
      const response = await request(app.getHttpServer())
        .post(`/projects/${projectId}/databases`)
        .set('Authorization', `Bearer ${authToken}`)
        .send({ name: 'main-db', type: 'oracle' })
        .expect(400);

      expect(response.body.message).toEqual(
        expect.arrayContaining([
          expect.stringContaining('Tipo de base de datos invalido'),
        ]),
      );
    });

    it('should reject invalid database name with special characters (400)', async () => {
      const response = await request(app.getHttpServer())
        .post(`/projects/${projectId}/databases`)
        .set('Authorization', `Bearer ${authToken}`)
        .send({ name: 'invalid db!', type: 'postgres' })
        .expect(400);

      expect(response.body.message).toEqual(
        expect.arrayContaining([
          expect.stringContaining(
            'El nombre solo puede contener letras, numeros, guiones y guiones bajos',
          ),
        ]),
      );
    });

    it('should successfully provision a PostgreSQL database (201)', async () => {
      const response = await request(app.getHttpServer())
        .post(`/projects/${projectId}/databases`)
        .set('Authorization', `Bearer ${authToken}`)
        .send({
          name: 'main-postgres',
          type: 'postgres',
          databaseName: 'my_app_prod',
          autoInjectEnv: true,
        })
        .expect(201);

      expect(response.body.id).toBe(databaseId);
      expect(response.body.name).toBe('main-postgres');
      expect(response.body.type).toBe('postgres');
      expect(response.body.port).toBe(5432);
      expect(response.body.status).toBe(DatabaseStatus.RUNNING);
      expect(response.body.connectionUrl).toContain('postgresql://');
    });
  });

  describe('GET /projects/:projectId/databases', () => {
    it('should reject requests without authorization token (401)', async () => {
      await request(app.getHttpServer())
        .get(`/projects/${projectId}/databases`)
        .expect(401);
    });

    it('should list all databases of the project (200)', async () => {
      const response = await request(app.getHttpServer())
        .get(`/projects/${projectId}/databases`)
        .set('Authorization', `Bearer ${authToken}`)
        .expect(200);

      expect(Array.isArray(response.body)).toBe(true);
      expect(response.body).toHaveLength(1);
      expect(response.body[0].name).toBe('main-postgres');
    });
  });

  describe('GET /projects/:projectId/databases/:id', () => {
    it('should return database details (200)', async () => {
      const response = await request(app.getHttpServer())
        .get(`/projects/${projectId}/databases/${databaseId}`)
        .set('Authorization', `Bearer ${authToken}`)
        .expect(200);

      expect(response.body.id).toBe(databaseId);
      expect(response.body.type).toBe('postgres');
    });

    it('should return 404 if database is not found', async () => {
      const nonexistentId = 'd0eebc99-9c0b-4ef8-bb6d-6bb9bd380a44';
      await request(app.getHttpServer())
        .get(`/projects/${projectId}/databases/${nonexistentId}`)
        .set('Authorization', `Bearer ${authToken}`)
        .expect(404);
    });
  });

  describe('GET /projects/:projectId/databases/:id/credentials', () => {
    it('should return credentials and connection URL (200)', async () => {
      const response = await request(app.getHttpServer())
        .get(`/projects/${projectId}/databases/${databaseId}/credentials`)
        .set('Authorization', `Bearer ${authToken}`)
        .expect(200);

      expect(response.body.host).toBe('titan_db_repo_main-postgres');
      expect(response.body.port).toBe(5432);
      expect(response.body.connectionUrl).toContain('postgresql://');
    });
  });

  describe('POST /projects/:projectId/databases/:id/stop and /start', () => {
    it('should stop the database container (200)', async () => {
      const response = await request(app.getHttpServer())
        .post(`/projects/${projectId}/databases/${databaseId}/stop`)
        .set('Authorization', `Bearer ${authToken}`)
        .expect(200);

      expect(response.body.status).toBe(DatabaseStatus.STOPPED);
    });

    it('should restart the database container (200)', async () => {
      const response = await request(app.getHttpServer())
        .post(`/projects/${projectId}/databases/${databaseId}/restart`)
        .set('Authorization', `Bearer ${authToken}`)
        .expect(200);

      expect(response.body.status).toBe(DatabaseStatus.RUNNING);
    });

    it('should start the database container (200)', async () => {
      const response = await request(app.getHttpServer())
        .post(`/projects/${projectId}/databases/${databaseId}/start`)
        .set('Authorization', `Bearer ${authToken}`)
        .expect(200);

      expect(response.body.status).toBe(DatabaseStatus.RUNNING);
    });
  });

  describe('DELETE /projects/:projectId/databases/:id', () => {
    it('should delete the database (200)', async () => {
      const response = await request(app.getHttpServer())
        .delete(`/projects/${projectId}/databases/${databaseId}`)
        .set('Authorization', `Bearer ${authToken}`)
        .expect(200);

      expect(response.body.message).toContain('eliminada exitosamente');

      await request(app.getHttpServer())
        .get(`/projects/${projectId}/databases/${databaseId}`)
        .set('Authorization', `Bearer ${authToken}`)
        .expect(404);
    });
  });
});
